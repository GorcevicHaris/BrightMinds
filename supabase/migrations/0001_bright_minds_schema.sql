-- -----------------------------------------------------------------------------
-- 4. Popunjavanje novih kolona iz starih beleški
--    "Nivo 3, Zvezdice: 2, Rezultat: 150"  →  level = 3, stars = 2, score = 150
--    Samo tamo gde je nova kolona prazna i samo vrednosti u dozvoljenom opsegu.
-- -----------------------------------------------------------------------------

with raw as (
    select id,
           substring(notes from 'Nivo\s+(\d+)')        as lvl,
           substring(notes from 'Zvezdice:\s*(\d+)')   as st,
           substring(notes from 'Rezultat:\s*(\d+)')   as sc
      from public.progress_logs
     where notes is not null
       and (level is null or stars is null or score is null)
),
parsed as (
    -- Ugnježdeni CASE garantuje da se tekst pretvara u broj tek posle provere dužine.
    select id,
           case when length(lvl) <= 2 then case when lvl::integer between 1 and 15 then lvl::integer end end as lvl,
           case when length(st)  =  1 then case when st::integer  between 0 and 3  then st::integer  end end as st,
           case when length(sc)  <= 9 then sc::integer end                                                  as sc
      from raw
)
update public.progress_logs p
   set level = coalesce(p.level, x.lvl),
       stars = coalesce(p.stars, x.st),
       score = coalesce(p.score, x.sc)
  from parsed x
 where p.id = x.id
   and (   (p.level is null and x.lvl is not null)
        or (p.stars is null and x.st  is not null)
        or (p.score is null and x.sc  is not null));

-- -----------------------------------------------------------------------------
-- 5. Jedinstveni indeksi (samo ako postojeći podaci to dozvoljavaju)
-- -----------------------------------------------------------------------------

do $$
declare
    v_duplicates bigint;
begin
    -- Email bez obzira na velika/mala slova. Postojeće adrese se NE menjaju.
    if to_regclass('public.users_email_lower_key') is null then
        select count(*) into v_duplicates
          from (select lower(email) from public.users group by lower(email) having count(*) > 1) d;
        if v_duplicates = 0 then
            create unique index users_email_lower_key on public.users (lower(email));
        else
            perform pg_temp.bm_note(format('jedinstveni indeks nad lower(email) NIJE napravljen: %s adresa postoji više puta (razlikuju se samo po velikim/malim slovima). Spojite ili obrišite duple naloge pa pokrenite migraciju ponovo.', v_duplicates));
        end if;
    end if;

    -- Tajni kod (vizuelni PIN) mora biti jedinstven, jer se dete prijavljuje samo njime.
    if to_regclass('public.children_pin_code_key') is null then
        select count(*) into v_duplicates
          from (select pin_code from public.children
                 where pin_code is not null and pin_code <> ''
                 group by pin_code having count(*) > 1) d;
        if v_duplicates = 0 then
            create unique index children_pin_code_key on public.children (pin_code)
                where pin_code is not null and pin_code <> '';
        else
            perform pg_temp.bm_note(format('jedinstveni indeks nad children.pin_code NIJE napravljen: %s tajnih kodova koristi više dece. Ta deca ne mogu da se prijave dok im roditelj ne izabere nove sličice. Spisak:  select pin_code, array_agg(id) from children where pin_code <> '''' group by pin_code having count(*) > 1;', v_duplicates));
        end if;
    end if;

    -- Jedna veza po paru (korisnik, dete).
    if to_regclass('public.user_children_user_child_key') is null then
        select count(*) into v_duplicates
          from (select user_id, child_id from public.user_children
                 group by user_id, child_id having count(*) > 1) d;
        if v_duplicates = 0 then
            create unique index user_children_user_child_key on public.user_children (user_id, child_id);
        else
            perform pg_temp.bm_note(format('jedinstveni indeks nad user_children (user_id, child_id) NIJE napravljen: %s parova postoji više puta.', v_duplicates));
        end if;
    end if;
end
$$;

