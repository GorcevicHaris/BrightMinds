--
-- ŠTA RADI
--   1. Pravi tabele users, children, user_children, activities i progress_logs
--      ako ne postoje (prazna baza).
--   2. U postojeće tabele dodaje kolone koje aplikacija koristi (niz dana, poeni,
--      nivo/zvezdice/rezultat partije...).
--   3. Upisuje 7 igara u `activities` (ID-jevi i nazivi iz lib/games.ts).
--   4. Popunjava nove kolone progress_logs.level/stars/score iz starih beleški
--      oblika "Nivo 3, Zvezdice: 2, Rezultat: 150".
--   5. Dodaje jedinstvene indekse, strane ključeve (ON DELETE CASCADE), obične
--      indekse i CHECK ograničenja.
--   6. Dodaje okidač koji održava children.updated_at.
--   7. Uključuje Row Level Security na svim tabelama (videti objašnjenje dole).
--
-- BEZBEDNA JE ZA PONAVLJANJE (idempotentna) I NIŠTA NE BRIŠE
--   Može da se pokrene i na praznoj i na postojećoj produkcijskoj bazi, više
--   puta. Ne briše i ne menja postojeće podatke, uz dva izuzetka koja samo
--   dopunjuju: popunjavanje praznih (NULL) kolona level/stars/score i usklađivanje
--   naziva 7 igara u `activities`.
--   Kada nešto ne može bezbedno da se doda (npr. dva deteta već imaju isti tajni
--   kod, pa jedinstveni indeks ne može da se napravi), migracija NE pada, već
--   zabeleži poruku: ispiše je kao NOTICE i prikaže u tabeli rezultata na kraju
--   (poslednja naredba u fajlu). Pročitajte poruke, ispravite podatke i pokrenite
--   migraciju ponovo. Poruke tipa "already exists, skipping" su očekivane.
--
-- KAKO SE POKREĆE
--   • Supabase Dashboard → SQL Editor → New query → nalepite ceo fajl → Run
--     (rezultat i poruke vide se u tabeli ispod upita), ili
--   • Supabase CLI:  supabase link --project-ref <ref>  pa  supabase db push
--
-- =============================================================================

