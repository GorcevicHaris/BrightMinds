    perform pg_temp.bm_add_fk('progress_logs', 'recorded_by', 'users',      'set null',  'progress_logs_recorded_by_fkey');
    perform pg_temp.bm_add_fk('progress_logs', 'activity_id', 'activities', 'no action', 'progress_logs_activity_id_fkey');
end
$$;

