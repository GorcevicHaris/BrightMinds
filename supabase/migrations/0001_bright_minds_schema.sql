-- -----------------------------------------------------------------------------
-- 8. CHECK ograničenja (NOT VALID — videti pg_temp.bm_add_check gore)
--    Poređenje ide preko ::text da radi i ako je kolona enum tip.
-- -----------------------------------------------------------------------------

do $$
begin
    perform pg_temp.bm_add_check('users', 'users_role_check',
        $c$role::text in ('parent', 'teacher', 'therapist', 'admin')$c$);

    -- Redovi dece se menjaju pri svakoj prijavi (niz dana, poeni), pa se ovo
    -- ograničenje dodaje samo ako ga nijedan postojeći red ne krši.
    perform pg_temp.bm_add_check('children', 'children_gender_check',
        $c$gender::text in ('male', 'female', 'other')$c$, true);

    perform pg_temp.bm_add_check('progress_logs', 'progress_logs_success_level_check',
        $c$success_level::text in ('struggled', 'partial', 'successful', 'excellent')$c$);
    perform pg_temp.bm_add_check('progress_logs', 'progress_logs_mood_before_check',
        $c$mood_before::text in ('very_upset', 'upset', 'neutral', 'happy', 'very_happy')$c$);
    perform pg_temp.bm_add_check('progress_logs', 'progress_logs_mood_after_check',
        $c$mood_after::text in ('very_upset', 'upset', 'neutral', 'happy', 'very_happy')$c$);
    perform pg_temp.bm_add_check('progress_logs', 'progress_logs_stars_check',
        $c$stars between 0 and 3$c$);
    perform pg_temp.bm_add_check('progress_logs', 'progress_logs_level_check',
        $c$level between 1 and 15$c$);
end
$$;

-- -----------------------------------------------------------------------------
-- 9. children.updated_at se osvežava pri svakoj izmeni
-- -----------------------------------------------------------------------------

create or replace function public.bm_set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $fn$
begin
    new.updated_at := now();
    return new;
end
$fn$;

do $$
begin
    if not exists (
        select 1 from pg_trigger
         where tgrelid = 'public.children'::regclass
           and tgname = 'children_set_updated_at'
           and not tgisinternal
    ) then
        create trigger children_set_updated_at
            before update on public.children
            for each row execute function public.bm_set_updated_at();
    end if;
end
$$;

-- -----------------------------------------------------------------------------
-- 10. Row Level Security
-- -----------------------------------------------------------------------------
-- RLS se UKLJUČUJE na svim tabelama, a NAMERNO se ne dodaje nijedno pravilo
-- (policy) za uloge `anon` i `authenticated`. Bez pravila te uloge ne mogu da
-- čitaju ni menjaju nijedan red.
--
-- Zašto: NEXT_PUBLIC_SUPABASE_ANON_KEY je javan — nalazi se u JavaScript-u koji
-- dobija svaki posetilac. Bez RLS-a bi bilo ko, tim ključem i Supabase REST
-- adresom, mogao direktno da čita i menja podatke o deci (i heševe lozinki),
-- potpuno mimo aplikacije.
--
-- Aplikacija bazi pristupa ISKLJUČIVO sa servera, service-role ključem
-- (SUPABASE_SERVICE_ROLE_KEY u lib/supabase.ts). Ta uloga zaobilazi RLS, pa
-- aplikacija radi kao i pre. To znači i da je SUPABASE_SERVICE_ROLE_KEY od sada
-- OBAVEZAN na serveru: sa samim anon ključem aplikacija više ne može do podataka.
--
-- Praćenje igre uživo (lib/realtime.ts) koristi Supabase Realtime BROADCAST
-- kanal: poruke idu od pregledača do pregledača i ne čitaju niti upisuju tabele,
-- pa RLS nad tabelama na njega ne utiče.

alter table public.users         enable row level security;
alter table public.children      enable row level security;
alter table public.user_children enable row level security;
alter table public.activities    enable row level security;
alter table public.progress_logs enable row level security;

commit;

-- Izveštaj: prvi red potvrđuje da je migracija prošla; ostali (ako ih ima) su
-- stavke koje nisu mogle bezbedno da se dodaju i šta treba uraditi.
select poruka as "Bright Minds — rezultat migracije"
  from pg_temp.bm_migration_report
 where run_at = (select max(run_at) from pg_temp.bm_migration_report)
 order by n;
