-- Beleži poruku u izveštaj i ispisuje je kao NOTICE.
create or replace function pg_temp.bm_note(p_message text) returns void
language plpgsql
as $fn$
begin
    insert into pg_temp.bm_migration_report (poruka) values (p_message);
    raise notice 'Bright Minds: %', p_message;
end
$fn$;

-- Dodaje strani ključ ako već ne postoji i ako nema redova koji bi ga prekršili.
create or replace function pg_temp.bm_add_fk(
    p_table text, p_column text, p_ref_table text, p_on_delete text, p_name text
) returns void
language plpgsql
as $fn$
declare
    v_existing   text;
    v_del_action "char";
    v_wanted     "char";
    v_orphans    bigint;
begin
    select c.conname, c.confdeltype
      into v_existing, v_del_action
      from pg_constraint c
      join pg_attribute a on a.attrelid = c.conrelid and a.attnum = c.conkey[1]
     where c.contype = 'f'
       and c.conrelid = format('public.%I', p_table)::regclass
       and c.confrelid = format('public.%I', p_ref_table)::regclass
       and array_length(c.conkey, 1) = 1
       and a.attname = p_column
     limit 1;

    if v_existing is not null then
        v_wanted := case lower(p_on_delete)
                        when 'cascade' then 'c' when 'set null' then 'n' when 'restrict' then 'r' else 'a'
                    end;
        if v_del_action <> v_wanted then
            perform pg_temp.bm_note(format('strani ključ %s (%s.%s) već postoji, ali nije ON DELETE %s. Ostavljen je kakav jeste; aplikacija radi i bez kaskade.', v_existing, p_table, p_column, upper(p_on_delete)));
        end if;
        return;
    end if;

    execute format(
        'select count(*) from public.%I t where t.%I is not null and not exists (select 1 from public.%I r where r.id = t.%I)',
        p_table, p_column, p_ref_table, p_column
    ) into v_orphans;

    if v_orphans > 0 then
        perform pg_temp.bm_note(format('strani ključ %s.%s -> %s.id NIJE dodat: %s redova pokazuje na nepostojeći zapis. Ispravite ili obrišite te redove pa pokrenite migraciju ponovo.', p_table, p_column, p_ref_table, v_orphans));
        return;
    end if;

    execute format(
        'alter table public.%I add constraint %I foreign key (%I) references public.%I (id) on delete %s',
        p_table, p_name, p_column, p_ref_table, p_on_delete
    );
exception when others then
    perform pg_temp.bm_note(format('strani ključ %s.%s -> %s.id nije dodat: %s', p_table, p_column, p_ref_table, sqlerrm));
end
$fn$;

-- Dodaje CHECK ograničenje kao NOT VALID (postojeći redovi se ne proveravaju,
-- pa "čudni" stari podaci ne obaraju migraciju). Ako nijedan red ne krši
-- pravilo, ograničenje se odmah i potvrđuje (VALIDATE).
-- p_skip_if_violated: ako postoje redovi koji krše pravilo, ograničenje se uopšte
-- ne dodaje. Koristi se za tabele čije redove aplikacija redovno menja, jer
-- Postgres pri SVAKOJ izmeni reda ponovo proverava sva CHECK ograničenja.
create or replace function pg_temp.bm_add_check(
    p_table text, p_name text, p_expr text, p_skip_if_violated boolean default false
) returns void
language plpgsql
as $fn$
declare
    v_violations bigint;
begin
    if exists (
        select 1 from pg_constraint
         where conrelid = format('public.%I', p_table)::regclass and conname = p_name
    ) then
        return;
    end if;

    execute format('select count(*) from public.%I where not (%s)', p_table, p_expr) into v_violations;

    if v_violations > 0 and p_skip_if_violated then
        perform pg_temp.bm_note(format('ograničenje %s NIJE dodato: %s redova u tabeli %s ga krši. Ispravite te redove pa pokrenite migraciju ponovo.', p_name, v_violations, p_table));
        return;
    end if;

    execute format('alter table public.%I add constraint %I check (%s) not valid', p_table, p_name, p_expr);

    if v_violations = 0 then
        execute format('alter table public.%I validate constraint %I', p_table, p_name);
    else
        perform pg_temp.bm_note(format('ograničenje %s dodato kao NOT VALID: %s postojećih redova u tabeli %s ga krši (ti redovi ne mogu da se menjaju dok se ne isprave).', p_name, v_violations, p_table));
    end if;
exception when others then
    perform pg_temp.bm_note(format('ograničenje %s nije dodato: %s', p_name, sqlerrm));
end
$fn$;

