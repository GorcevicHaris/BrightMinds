-- =============================================================================
-- Bright Minds — migracija 0003: „Moje priče” (priče koje piše odrasli)
-- =============================================================================
--
-- ŠTA RADI
--   1. Pravi tabelu custom_stories: kratke priče koje roditelj ili terapeut piše
--      za jedno dete (naslov, sličica i 2–8 koraka). Dete ih čita ili sluša korak
--      po korak, bez pitanja i bez bodovanja.
--        • steps je jsonb niz oblika [{ "text": "…", "emoji": "🦷" | null }, …];
--          oblik i ograničenja dužine proverava aplikacija (lib/customStories.ts).
--        • created_by je nalog koji je priču napisao (prazni se ako se nalog obriše).
--   2. Dodaje strane ključeve: brisanje deteta briše i njegove priče
--      (ON DELETE CASCADE), brisanje naloga samo prazni created_by (SET NULL).
--   3. Dodaje indeks (child_id, updated_at desc) za spisak priča jednog deteta.
--   4. Dodaje okidač koji održava custom_stories.updated_at (ista funkcija
--      public.bm_set_updated_at kao za children u migraciji 0001).
--   5. Uključuje Row Level Security bez ijednog pravila — tabeli pristupa samo
--      server (service-role ključ), kao i ostalim tabelama (videti 0001, odeljak 10).
--
-- PREDUSLOV
--   Tabele children i users moraju da postoje. Na praznoj bazi prvo pokrenite
--   0001_bright_minds_schema.sql.
--
-- BEZBEDNA JE ZA PONAVLJANJE (idempotentna) I NIŠTA NE BRIŠE
--   Samo dodaje novu tabelu i ono što uz nju ide, ako već ne postoji. Postojeće
--   tabele i redovi se ne menjaju. Ako strani ključ ne može da se doda, migracija
--   NE pada, već zabeleži poruku: ispiše je kao NOTICE i prikaže u tabeli
--   rezultata na kraju. Poruke tipa "already exists, skipping" su očekivane.
--
-- BEZ OVE MIGRACIJE aplikacija i dalje radi: dete ne vidi odeljak „Moje priče”
--   (spisak je prazan), a čuvanje priče vraća grešku 409 sa uputstvom da se
--   pokrene ova migracija.
--
-- KAKO SE POKREĆE
--   • Supabase Dashboard → SQL Editor → New query → nalepite ceo fajl → Run, ili
--   • Supabase CLI:  supabase link --project-ref <ref>  pa  supabase db push
--
-- =============================================================================

begin;

-- -----------------------------------------------------------------------------
-- Preduslov: tabele iz migracije 0001
-- -----------------------------------------------------------------------------

do $$
begin
    if to_regclass('public.children') is null or to_regclass('public.users') is null then
        raise exception 'Bright Minds: tabele children i users ne postoje. Prvo pokrenite migraciju 0001_bright_minds_schema.sql.';
    end if;
end
$$;

-- -----------------------------------------------------------------------------
-- Izveštaj (živi samo u ovoj sesiji; isti oblik kao u migracijama 0001 i 0002)
-- -----------------------------------------------------------------------------

create temporary table if not exists bm_migration_report (
    n      integer generated always as identity,
    run_at timestamptz not null default now(),
    poruka text not null
);

insert into pg_temp.bm_migration_report (poruka)
values ('Migracija 0003 je primenjena. Ako ispod ima još redova, to su stavke koje traže vašu pažnju.');

-- -----------------------------------------------------------------------------
-- 1. Tabela (samo ako ne postoji)
-- -----------------------------------------------------------------------------

create table if not exists public.custom_stories (
    id         bigint generated by default as identity primary key,
    child_id   bigint not null,
    title      text not null,
    emoji      text,
    steps      jsonb not null default '[]'::jsonb,
    created_by bigint,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint custom_stories_steps_check check (jsonb_typeof(steps) = 'array')
);

comment on table public.custom_stories is
    'Priče koje odrasli piše za jedno dete („Moje priče”). Oblik i ograničenja: lib/customStories.ts.';
comment on column public.custom_stories.steps is
    'Koraci priče: jsonb niz [{ "text": "…", "emoji": "…" | null }]. Aplikacija dozvoljava 2–8 koraka.';
comment on column public.custom_stories.created_by is
    'Nalog (users.id) koji je priču napisao; NULL ako je nalog obrisan.';

-- -----------------------------------------------------------------------------
-- 2. Strani ključevi
--    Brisanje deteta briše i njegove priče; brisanje naloga samo prazni polje
--    "ko je napisao". Dodaju se odvojeno od tabele da greška (npr. children.id
--    bez primarnog ključa u staroj bazi) ne obori celu migraciju.
-- -----------------------------------------------------------------------------

do $$
declare
    v_message text;
begin
    if not exists (
        select 1 from pg_constraint
         where conrelid = 'public.custom_stories'::regclass
           and conname = 'custom_stories_child_id_fkey'
    ) then
        begin
            alter table public.custom_stories
                add constraint custom_stories_child_id_fkey
                foreign key (child_id) references public.children (id) on delete cascade;
        exception when others then
            v_message := format('strani ključ custom_stories.child_id -> children.id nije dodat: %s. Priče rade, ali se ne brišu automatski kada se obriše dete.', sqlerrm);
            insert into pg_temp.bm_migration_report (poruka) values (v_message);
            raise notice 'Bright Minds: %', v_message;
        end;
    end if;

    if not exists (
        select 1 from pg_constraint
         where conrelid = 'public.custom_stories'::regclass
           and conname = 'custom_stories_created_by_fkey'
    ) then
        begin
            alter table public.custom_stories
                add constraint custom_stories_created_by_fkey
                foreign key (created_by) references public.users (id) on delete set null;
        exception when others then
            v_message := format('strani ključ custom_stories.created_by -> users.id nije dodat: %s. Priče rade i bez njega.', sqlerrm);
            insert into pg_temp.bm_migration_report (poruka) values (v_message);
            raise notice 'Bright Minds: %', v_message;
        end;
    end if;
end
$$;

-- -----------------------------------------------------------------------------
-- 3. Indeks: priče jednog deteta, najnovije prvo
-- -----------------------------------------------------------------------------

create index if not exists custom_stories_child_updated_idx
    on public.custom_stories (child_id, updated_at desc);

-- -----------------------------------------------------------------------------
-- 4. custom_stories.updated_at se osvežava pri svakoj izmeni
--    Funkciju public.bm_set_updated_at pravi migracija 0001 (odeljak 9); ovde se
--    pravi samo ako nedostaje, u istom obliku.
-- -----------------------------------------------------------------------------

do $$
begin
    if to_regprocedure('public.bm_set_updated_at()') is null then
        create function public.bm_set_updated_at()
        returns trigger
        language plpgsql
        set search_path = ''
        as $fn$
        begin
            new.updated_at := now();
            return new;
        end
        $fn$;
    end if;

    if not exists (
        select 1 from pg_trigger
         where tgrelid = 'public.custom_stories'::regclass
           and tgname = 'custom_stories_set_updated_at'
           and not tgisinternal
    ) then
        create trigger custom_stories_set_updated_at
            before update on public.custom_stories
            for each row execute function public.bm_set_updated_at();
    end if;
end
$$;

-- -----------------------------------------------------------------------------
-- 5. Row Level Security
--    Uključen, bez pravila za uloge `anon` i `authenticated` — javnim ključem se
--    priče ne mogu ni čitati ni menjati. Aplikacija im pristupa samo sa servera,
--    service-role ključem (objašnjenje u migraciji 0001, odeljak 10).
-- -----------------------------------------------------------------------------

alter table public.custom_stories enable row level security;

commit;

-- Supabase API (PostgREST) pamti spisak tabela; ovim ga odmah osvežavamo da
-- aplikacija vidi novu tabelu bez čekanja. Van Supabase-a naredba ne radi ništa.
notify pgrst, 'reload schema';

-- Izveštaj: prvi red potvrđuje da je migracija prošla; ostali (ako ih ima) su
-- stavke koje nisu mogle bezbedno da se dodaju i šta treba uraditi.
select poruka as "Bright Minds — rezultat migracije"
  from pg_temp.bm_migration_report
 where run_at = (select max(run_at) from pg_temp.bm_migration_report)
 order by n;
